package com.unilost.entity;

import jakarta.persistence.*;

/**
 * Represents a row in the "users" table.
 * A user can be a normal STUDENT or an ADMIN.
 */
@Entity
@Table(name = "users")
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String fullName;

    @Column(nullable = false, unique = true)
    private String email;

    // Stored as a SHA-256 hash, never plain text (see util/PasswordUtil.java)
    @Column(nullable = false)
    private String password;

    // Role is either "STUDENT" or "ADMIN"
    @Column(nullable = false)
    private String role = "STUDENT";

    // email_verified — always true since we removed OTP verification
    @Column(nullable = false)
    private boolean emailVerified = true;

    // enabled — account is active
    @Column(nullable = false)
    private boolean enabled = true;

    // Optional - shown on the profile page
    private String collegeName;

    public User() {
    }

    public User(String fullName, String email, String password, String role) {
        this.fullName = fullName;
        this.email = email;
        this.password = password;
        this.role = role;
    }

    // ----- Getters and Setters -----

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public String getCollegeName() {
        return collegeName;
    }

    public void setCollegeName(String collegeName) {
        this.collegeName = collegeName;
    }

    public boolean isEmailVerified() {
        return emailVerified;
    }

    public void setEmailVerified(boolean emailVerified) {
        this.emailVerified = emailVerified;
    }

    public boolean isEnabled() {
        return enabled;
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
    }
}
